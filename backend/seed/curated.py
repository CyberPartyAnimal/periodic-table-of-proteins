def V(change, disease, note=None):
    return {"change": change, "disease": disease, "note": note}


def P(symbol, name, gene, uniprot, family, loc, year, milestone, blurb, *,
      pathways=(), drugs=(), therapeutic=None, variants=(), ecoli=None, yeast=None,
      other_locs=(), misfold=None, mass=None, length=None):
    return {
        "symbol": symbol, "name": name, "gene": gene, "uniprot": uniprot,
        "family": family, "location": loc, "year": year, "milestone": milestone,
        "blurb": blurb, "pathways": list(pathways), "drugs": list(drugs),
        "therapeutic": therapeutic, "variants": list(variants), "ecoli": ecoli,
        "yeast_override": yeast,
        "other_locations": list(other_locs), "misfold": misfold,
        "mass_override": mass, "length_override": length,
    }


def MF(symbol, name, kind, diseases, description, pdb=None, drugs=()):
    """A misfolded conformer: same sequence as the native protein, different fold."""
    return {"symbol": symbol, "name": name, "kind": kind, "diseases": list(diseases),
            "description": description, "pdb": pdb, "drugs": list(drugs)}


